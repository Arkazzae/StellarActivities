function compileChannel(
  channelId: DiplomaticChannelId,
  prefix: string,
  drafts: readonly EventDraft[],
): DiplomaticEventDefinition[] {
  return drafts.map((draft, index) => {
    const choiceSet = CHOICE_SETS[draft.set];
    if (choiceSet.channelId !== channelId) {
      throw new Error(`Zestaw ${draft.set} nie należy do kanału ${channelId}.`);
    }
    return {
      id: `${prefix}-${String(index + 1).padStart(2, "0")}`,
      channelId,
      title: draft.title,
      message: draft.message,
      artKey: choiceSet.artKey,
      liaisonRole: draft.liaisonRole,
      intensity: draft.intensity,
      choices: choiceSet.choices.map((choice) => ({
        ...choice,
        effects: { ...choice.effects },
        hiddenEffects: { ...choice.hiddenEffects },
        response: `${draft.reply} ${choice.response}`,
      })),
    };
  });
}

