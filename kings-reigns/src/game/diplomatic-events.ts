export function publicDiplomaticEvent(event: DiplomaticEventDefinition): PublicDiplomaticEvent {
  return {
    id: event.id,
    channelId: event.channelId,
    title: event.title,
    message: event.message,
    art: `assets/diplomatic-events/${event.artKey}.webp`,
    liaisonRole: event.liaisonRole,
    intensity: event.intensity,
    choices: event.choices.map((choice) => ({
      id: choice.id,
      label: choice.label,
      description: choice.description,
      effects: { ...choice.effects },
      relationDelta: choice.relationDelta,
    })),
  };
}
