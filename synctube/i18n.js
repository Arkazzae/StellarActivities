export const LANGUAGE_NAMES = { en: "English", pl: "Polski" };

export function resolveLanguage(locale) {
  return String(locale || "").toLowerCase().startsWith("pl") ? "pl" : "en";
}

export function translator(language) {
  const strings = language === "pl" ? pl : en;
  return (key, ...args) => {
    const value = Object.hasOwn(strings, key) ? strings[key] : en[key];
    if (typeof value === "function") return value(...args);
    return value ?? key;
  };
}

