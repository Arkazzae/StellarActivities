export type Lang = "pl" | "en";

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let text = (lang === "en" ? en[key] : undefined) ?? pl[key] ?? key;
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export const LangContext = createContext<Lang>("pl");

export function useT() {
  const lang = useContext(LangContext);
  return (key: Key, params?: Record<string, string | number>) => translate(lang, key, params);
}

export const langFromLocale = (locale: string | null | undefined): Lang => (String(locale ?? "").toLowerCase().startsWith("pl") ? "pl" : "en");
